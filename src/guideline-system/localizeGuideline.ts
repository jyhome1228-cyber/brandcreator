export function localizeGuidelinePages(pages: GuidelinePage[], language: DocumentLanguage): GuidelinePage[] {
  if (language === 'ko') return pages;
  // Restrict replacement to known system copy. Custom brand input is not machine-translated.
  const dictionary = [...templateCopy].sort((a,b) => b[0].length - a[0].length);
  const translate = (value: string) => dictionary.reduce((text,[ko,en]) => text.split(ko).join(en), value);
  return pages.map(page => ({ ...page, title: translate(page.title), subtitle: translate(page.subtitle), svg: translate(page.svg) }));
}
